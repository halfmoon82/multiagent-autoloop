// 调度会话【任务】段：以 git 中已存在的 open 事项（issues/PR）为核心，状态扫描降为辅助。
// 独立模块，避免与 scheduling-session.mjs 的其他改动冲突。
export function buildOpenItemsTasks({ project } = {}) {
  return [
    `【任务】开局先读 open 事项，再逐项判断推进方式；调度会话的职责是把 git 中已存在的 open issue/PR 用调度方式推进：派发、跟踪、收敛。`,
    `1）读上下文：你的工作目录就是该项目仓库（${project}）。阅读本仓库的 AGENTS.md、README.md 与 docs/ 建立项目上下文（边界、命令、约定），以磁盘文件为准。`,
    `2）读 open 事项：用 gh issue list --state open 与 gh pr list --state open（含标签、指派、关联分支、CI 与评审状态）列出全部 open issue 与 PR；gh 不可用时改读本地分支与 .git 中可得信息并在会话中说明局限。逐项判断推进方式并写明依据，每项归入下列之一：`,
    `   - 派发：尚无人推进且边界清晰的 issue，按护栏第 4、6 条拆解任务、选择模型、开独立 worktree 派发 worker。`,
    `   - 跟踪：已有 worker/分支/PR 在推进的事项，核对进度、CI 与评审状态，停滞或失败时按重试纪律换打法。`,
    `   - 收敛：交付已完成的 PR，审阅后推进到可合并（合并授权按项目约定），关闭已解决的 issue，清理已合并分支与 worktree。`,
    `   - 挂起：被外部条件阻塞的事项，写明阻塞原因；仅当属于护栏第 2 条的两类问题时才升级给用户。`,
    `3）状态扫描（辅助）：需要判断某事项为何卡住、是否有失败任务或待处理卡片时，再用 list_rules / list_runs / list_cards 查询调度状态作为佐证，不要把全局扫描当作开局主线。自愈闭环：诊断出可自愈的问题并修复（限本地调度脚本/配置/状态/规则，不动项目代码）、做最小验证后，用 resume_rule / run_rule 恢复或重触发对应规则，遵守重试纪律。若 MCP 工具不可用，可用控制台 API（http://127.0.0.1:50761，仅本机）兜底读取同一状态（沙箱可能拦截命令行 HTTP 请求，优先走 MCP 工具）。`,
    `4）目标项目的代码改动由派发 worker 在隔离 worktree 中执行；本会话只读诊断与协调，不直接改项目文件（实现边界见护栏第 6 条）。需要授权或不可逆操作时只列出等待用户决策，且遵守卡片陈述规则。`,
    `5）汇报：以事项为单位给出处理清单（编号、推进方式、当前状态、下一步），而不是调度状态流水。`,
  ];
}
